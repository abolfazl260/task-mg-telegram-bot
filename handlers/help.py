"""User guide command and main-menu help content."""

from telegram import Update
from telegram.ext import ContextTypes


HELP_TEXT = """# 📖 راهنمای کامل Task Manager Bot

این راهنما به‌صورت Instant View نمایش داده می‌شود تا بتوانید سریع همه قابلیت‌ها را مرور کنید.

## ➕ افزودن تسک

از دکمه «افزودن تسک» ابتدا انتخاب می‌کنید که تسک را تکی ثبت کنید یا آپلود گروهی انجام دهید.

### ثبت تکی

۱) عنوان تسک را بنویسید.
۲) حتماً یکی از سه اولویت بالا، متوسط یا پایین را انتخاب کنید.
۳) زمان انجام را انتخاب کنید یا بدون زمان‌بندی ادامه دهید.
۴) برای دسته‌بندی، لیست دسته‌های قبلی به‌صورت دکمه نمایش داده می‌شود؛ اگر دسته‌بندی جدید می‌خواهید فقط نام آن را ارسال کنید تا ساخته شود. تگ و توضیح اختیاری هستند و با دکمه «رد کردن» قابل عبورند.
۵) در پایان می‌توانید مسئول را مشخص کنید یا تسک را بدون مسئول ثبت کنید.

### ایمپورت گروهی

ایمپورت گروهی دو روش دارد:

#### 📝 ورود متنی

فرمت هر خط این است:

```text
TASKS
خرید نان | medium |  | خرید |  | ۲ عدد
```

ترتیب ستون‌ها: عنوان | اولویت | مهلت | دسته | تگ | توضیح

#### 📄 آپلود CSV

مسیر ساده استفاده: **دانلود نمونه → ویرایش → ذخیره به CSV → ارسال فایل به ربات → بررسی → تأیید → ایجاد تسک‌ها**.

در بخش ایمپورت گروهی روی «دانلود فایل نمونه CSV» بزنید، فایل را با Excel / Google Sheets / Numbers ویرایش کنید و دوباره فایل CSV را برای ربات بفرستید. ربات ابتدا کل فایل را اعتبارسنجی می‌کند و تا قبل از تأیید شما هیچ تسکی ایجاد نمی‌شود. اگر خطایی وجود داشته باشد، شماره ردیف، ستون و علت خطا نمایش داده می‌شود.

ستون‌های CSV:

```text
title,priority,deadline,category,tags,description
```

قوانین: title الزامی است؛ priority فقط high، medium یا low؛ deadline تاریخ معتبر مثل 2026-08-20 یا خالی است.

## 📋 مدیریت تسک‌ها

از بخش «تسک‌ها» می‌توانید لیست فعال، مرتب‌سازی بر اساس ددلاین/اولویت/تاریخ ایجاد، گزارش بر اساس تگ یا دسته‌بندی و خروجی Excel را ببینید.

## 👥 تیم‌ها و اشتراک دسته‌بندی

برای همکاری تیمی، یک دسته‌بندی مشترک بسازید یا دسته‌بندی موجود خود را به اشتراک بگذارید. قابلیت اشتراک‌گذاری لیست از منوی تیم‌ها و دکمه‌های همان بخش انجام می‌شود.

## 👤 Guest Bots / Guest Mode

Guest Mode یا Guest Bots برای زمانی است که می‌خواهید بدون اضافه‌کردن ربات به گروه، کانال یا چت‌های پشتیبانی‌شده، همان‌جا از ربات استفاده کنید. با فعال‌سازی این قابلیت در BotFather، کاربر فقط نام کاربری ربات را داخل چت می‌نویسد و ربات به‌صورت مهمان پاسخ آماده می‌کند.

### کاربردهای Guest Mode

- ثبت سریع تسک از داخل هر گروه، بدون اینکه ربات عضو گروه باشد.
- تبدیل پیام‌های کاری گروه به تسک شخصی برای همان کاربری که ربات را صدا زده است.
- ساخت دسته‌بندی خودکار بر اساس نام چت؛ تسک‌های مهمان با دسته‌ای مثل `Guest: نام گروه` ثبت می‌شوند.
- افزودن تگ `guest` برای اینکه بعداً بتوانید تسک‌های ساخته‌شده از گروه‌ها را راحت‌تر پیدا کنید.
- ارسال گزارش مهم داخل گروه بدون اضافه‌کردن ربات به گروه.

### روش فعال‌سازی

۱) در BotFather وارد تنظیمات ربات شوید.
۲) از بخش Mini App / قابلیت‌های ربات، Guest Mode را فعال کنید.
۳) مطمئن شوید نام کاربری ربات مشخص است؛ سپس در چت مقصد نام ربات را همراه دستور یا متن تسک بنویسید.

### حالت ثبت تسک مهمان

نمونه‌ها:

```text
@YourBot add پیگیری قرارداد 2026-08-20 فوری
@YourBot تسک تماس با مشتری فردا مهم
@YourBot خرید تجهیزات low 2026-08-25
```

ربات عنوان تسک را از متن استخراج می‌کند، اولویت را اگر کلماتی مثل `فوری`، `مهم`، `متوسط`، `پایین`، `high`، `medium` یا `low` نوشته باشید تشخیص می‌دهد و تاریخ‌هایی مثل `2026-08-20` را به‌عنوان ددلاین ثبت می‌کند. اگر اولویت مشخص نشود، اولویت پیش‌فرض `medium` است و اگر تاریخ نباشد تسک بدون ددلاین ساخته می‌شود.

### حالت گزارش مهم

برای گرفتن خلاصه وضعیت در همان چت بنویسید:

```text
@YourBot گزارش مهم
@YourBot report
@YourBot status
```

گزارش مهم شامل تعداد کل تسک‌ها، تسک‌های فعال، اولویت بالا، موعد امروز، عقب‌افتاده‌ها و چند مورد مهم برای پیگیری سریع است.

### محدودیت‌ها و نکات

- تسک مهمان برای حساب همان کاربری ثبت می‌شود که ربات را صدا زده است، نه برای همه اعضای گروه.
- ربات پیام‌های گروه را نمی‌خواند؛ فقط همان درخواست Guest Mode را پردازش می‌کند.
- اگر متن فقط نام ربات باشد و عنوان تسک نداشته باشد، ربات نمونه فرمت صحیح را نمایش می‌دهد.
- برای مدیریت کامل، تغییر وضعیت، ویرایش یا خروجی گرفتن، از چت خصوصی ربات و منوی اصلی استفاده کنید.

## 🧩 تمپلیت‌ها

برای ساخت سریع‌تر کارهای تکراری از تمپلیت‌های آماده استفاده کنید.

## 🌱 عادت‌ها

با دستور /habit یا دکمه «مدیریت عادت‌ها» عادت‌های روزانه/هفتگی/ماهانه را تعریف کنید، یادآوری بگذارید و وضعیت انجام آن‌ها را پیگیری کنید.

## 🤖 دستیار هوشمند

اگر `GROQ_API_KEY` تنظیم شده باشد، با `/ai سؤال شما` می‌توانید درباره اولویت‌بندی، تمرکز امروز یا مرور تسک‌ها از دستیار Groq کمک بگیرید. مثال: `/ai امروز روی چه کاری تمرکز کنم؟`

## 📊 گزارشات

گزارش‌های وضعیت، اولویت، دسته‌بندی، مسئول، هفته جاری، عملکرد و پیشرفت برای بررسی بهتر کارها در دسترس است. از بخش گزارشات می‌توانید نمای کلی وضعیت کارها را ببینید و از بخش تسک‌ها نیز گزارش‌های دسته‌بندی، تگ، مسئول و خروجی Excel بگیرید. برای ارسال گزارش مهم در گروه بدون اضافه‌کردن بات، Guest Mode را در BotFather فعال کنید و در گروه بنویسید: `@YourBot گزارش مهم`.

## ⚙️ تنظیمات

در بخش تنظیمات می‌توانید منطقه زمانی خود را انتخاب کنید تا یادآوری‌ها و زمان‌بندی‌ها بر اساس ساعت محلی شما مدیریت شوند.

## 💙 دونیت و ارتباط با ما

دونیت از بخش «ارتباط با ما» در منوی اصلی در دسترس است. در همان بخش می‌توانید برای حمایت مالی، ارسال پیشنهاد، سفارش ربات اختصاصی یا مشاهده سایر ربات‌ها و خدمات با ما در ارتباط باشید.

## 🔎 جستجو

با دستور /search می‌توانید در عنوان، دسته، تگ و توضیح تسک‌ها جستجو کنید.

## 📌 خلاصه امکانات منوی اصلی

- افزودن تسک تکی و آپلود گروهی
- مشاهده، مرتب‌سازی، گزارش‌گیری و خروجی Excel از تسک‌ها
- تیم‌ها و اشتراک دسته‌بندی برای همکاری گروهی
- تمپلیت‌ها برای کارهای تکراری
- مدیریت عادت‌ها و پیگیری روتین‌ها
- گزارشات کامل وضعیت و عملکرد
- تنظیم منطقه زمانی
- Guest Mode برای ثبت تسک و گزارش مهم از گروه‌ها
- ارتباط با ما و دونیت
"""


async def help_command(update: Update, context: ContextTypes.DEFAULT_TYPE):
    message = update.effective_message
    await context.bot._post(
        "sendRichMessage",
        data={
            "chat_id": update.effective_chat.id,
            "rich_message": {"markdown": HELP_TEXT},
        },
    )
    await message.reply_text("📖 راهنما نمایش داده شد.")
